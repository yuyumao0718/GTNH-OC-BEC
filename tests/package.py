"""Create the OpenOS bundle without development dependencies or runtime state."""
from pathlib import Path
from zipfile import ZipFile, ZIP_DEFLATED

root = Path(__file__).resolve().parents[1]
programs = sorted(root.glob('*.lua'))
files = programs + [root / '使用说明.md', root / '测试说明.md', root / '配置界面与加工逻辑实施方案.md', root / 'serve-local.cmd']
files += sorted((root / 'wiki').glob('*.html')) + sorted((root / 'wiki').glob('*.png'))
files += sorted((root / 'examples').glob('*.lua'))
installer = root / 'install' / 'multi_install.lua'
installer.parent.mkdir(exist_ok=True)

def literal(text):
    equals = '='
    while ']' + equals + ']' in text:
        equals += '='
    return '[' + equals + '[\n' + text + ']' + equals + ']'

header = '''-- Generated by tests/package.py; contains the complete standalone program.
local fs = require('filesystem')
local shell = require('shell')
local args = { ... }
local dir = shell.resolve(args[1] or '/home/bec')
local files = {}
'''
payload = ''.join("files[#files + 1] = {\n    name = '" + p.name + "',\n    code = " + literal(p.read_text(encoding='utf-8')) + ',\n}\n' for p in programs)
footer = '''assert(fs.isDirectory(dir) or fs.makeDirectory(dir), '无法创建安装目录：' .. dir)
for _, file in ipairs(files) do
    local path = dir .. '/' .. file.name
    local f, err = io.open(path, 'w')
    assert(f, '无法写入程序文件：' .. path .. ' / ' .. tostring(err))
    assert(f:write(file.code))
    assert(f:flush())
    f:close()
end
print('安装完成：' .. dir .. '（' .. #files .. ' 个程序文件）')
print('接下来依次执行以下命令，完成配置和启动：')
print('cd ' .. dir)
print('bec_multi.lua setup')
print('bec_multi.lua run')
'''
installer.write_text(header + payload + footer, encoding='utf-8', newline='\n')
print(f'{installer}: {len(programs)} embedded files')
destination = root / 'multi-array-openos.zip'
with ZipFile(destination, 'w', ZIP_DEFLATED) as archive:
    for path in files:
        archive.write(path, 'multi-array/' + path.relative_to(root).as_posix())
    archive.write(installer, 'multi-array/install/multi_install.lua')
print(f'{destination}: {len(files) + 1} files')
